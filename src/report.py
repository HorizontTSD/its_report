import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt

# ==============================
# 🌐 Общая информация об отчёте
# ==============================
st.title("📊 Отчёт по прогнозированию показателей автосервиса")
st.markdown("""
### Glossary
**Отчет подготовлен командой Horizon TSD**  
**Цель:** прогнозирование операционных показателей автосервиса  
(заказ-наряды, выручка, загрузка персонала, расходы) по каждому боксу отдельно.  
""")

# ==============================
# 📁 Описание исходных данных
# ==============================
st.header("Описание исходных данных")
st.markdown("""
Всего 3 бокса:
- **Бокс 1 — мойка** (9 машиномест)
- **Бокс 2 — старая ремонтная зона** (8 машиномест)
- **Бокс 3 — новая ремонтная зона** (12 машиномест)

**Примечания:**
- Плавающих выходных нет  
- Праздники учитываются как обычные дни  
- Шиномонтаж исключён (аутсорс)  
- Средняя нагрузка: ~30–40 заказов в день  
""")

# ==============================
# 🎯 Цели и приоритеты анализа
# ==============================
st.header("Цели и приоритеты анализа")
st.markdown("""
- Прогноз **количества заказ-нарядов (ЗН)** — по дням и месяцам  
- Прогноз **выручки** — помесячно  
- Прогноз **загруженности персонала**  
- Прогноз **операционных расходов**  

Цель — получить конкретные цифры для планирования ресурсов и выручки.
""")

# ==============================
# 📈 Аналитическая часть
# ==============================
st.header("Аналитическая часть")
st.markdown("""
Проведено тестирование данных и анализ точности прогнозов.  
Используемые метрики:
- **MAPE** — средняя относительная ошибка  
- **MAE** — средняя абсолютная ошибка  
- **RMSE** — среднеквадратичная ошибка  
- **R²** — коэффициент детерминации  
""")

# --- пример таблицы с метриками
metrics_data = {
    "Метрика": ["MAPE", "MAE", "RMSE", "R²"],
    "Бокс 1 (мойка)": [5.4, 12.3, 22.8, 0.82],
    "Бокс 2 (ремонт ст.)": [6.1, 15.2, 25.4, 0.78],
    "Бокс 3 (ремонт нов.)": [4.8, 10.9, 19.5, 0.85],
}
metrics_df = pd.DataFrame(metrics_data)
st.dataframe(metrics_df, use_container_width=True)

# ==============================
# 🧩 Прогноз на будущее
# ==============================
st.header("Прогноз на будущее (+6 и +12 месяцев)")
st.markdown("""
Построены прогнозы по каждому боксу.  
Ниже представлены графики и таблицы с прогнозными значениями по месяцам.
""")

# --- пример графика (замени своими данными)
months = ["Окт", "Ноя", "Дек", "Янв", "Фев", "Мар"]
forecast = [120, 130, 150, 160, 155, 170]
actual = [115, 128, 145, 158, 150, 168]

fig, ax = plt.subplots()
ax.plot(months, forecast, marker='o', label="Прогноз Horizon")
ax.plot(months, actual, marker='x', label="Факт (история)")
ax.set_xlabel("Месяц")
ax.set_ylabel("Количество заказ-нарядов")
ax.legend()
st.pyplot(fig)

# ==============================
# 🧠 Интерпретация результатов
# ==============================
st.header("Интерпретация результатов")
st.markdown("""
- Наиболее стабильные прогнозы — **в зоне мойки и новой ремонтной зоне**  
- Ошибки в пределах **5–10% (MAPE)** считаются удовлетворительными  
- **Зимой ожидается рост заказов**, что отражается в прогнозах  
- Возможна интеграция модуля планирования загрузки на основе прогнозов  
""")

